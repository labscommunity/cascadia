#!/usr/bin/env bash
# Regenerate tools/export-locks/*.txt, the exact versions and hashes
# `cascadia python setup` installs, from tools/requirements.txt and
# tools/requirements-managed.txt. A unit test fails until this is re-run after
# either file changes. Needs uv on PATH.
#
#   scripts/update-export-locks.sh
#
# Each lock covers Python 3.12 and 3.13; the package sets are the same on both.
set -euo pipefail

cd "$(dirname "$0")/.."
stamp="$(cat tools/requirements.txt tools/requirements-managed.txt | tr -d '\r' | shasum -a 256 | cut -d' ' -f1)"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

compile() { # <lock name> <uv --python-platform>
    # torch's macOS arm64 wheels start at 14.0; uv assumes 13.0 unless told.
    MACOSX_DEPLOYMENT_TARGET=14.0 uv pip compile \
        tools/requirements.txt tools/requirements-managed.txt \
        --no-config --python-platform "$2" --python-version 3.12 \
        --torch-backend cpu --only-binary :all: \
        --no-emit-package openvino-telemetry \
        --generate-hashes --no-annotate --no-header --quiet \
        --output-file "$tmp/$1.txt"
    {
        echo "# Generated by scripts/update-export-locks.sh; do not edit."
        echo "# requirements-sha256: $stamp"
        sed '/^# The following packages were excluded/,$d' "$tmp/$1.txt"
    } >"tools/export-locks/$1.txt"
    echo "$1: $(grep -cE '^[A-Za-z0-9]' "tools/export-locks/$1.txt") packages"
}

compile linux-x86_64 x86_64-manylinux_2_28
compile windows-x86_64 x86_64-pc-windows-msvc
compile macos-arm64 aarch64-apple-darwin
