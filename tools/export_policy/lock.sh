#!/usr/bin/env bash
# Regenerate the hashed requirement files `cascadia export-policy` embeds (needs uv >= 0.13.6). Run
# from anywhere; commit all outputs together with any change to pyproject.toml or LOCK_DATE.
#   requirements.txt            the export environment (Python 3.12, Linux, Windows and macOS)
#   requirements-preflight.txt  huggingface-hub alone, at the same versions, for the checks that
#                               run before anything large is downloaded
#   build-constraints.txt       the build backends of the two git packages and the sdist-only
#                               wheels (hatchling, hatch-vcs, setuptools), for --require-build-hashes
# Not --no-config: the [tool.uv] table of pyproject.toml carries the override and sources.
# LOCK_DATE (--exclude-newer) makes a relock with unchanged inputs reproduce the same files.
set -euo pipefail
cd "$(dirname "$0")"
LOCK_DATE=2026-11-16T00:00:00Z
compile=(uv pip compile --quiet --generate-hashes --universal --python-version 3.12
         --no-header --exclude-newer "$LOCK_DATE")
header='# Generated by tools/export_policy/lock.sh. Do not edit.'
"${compile[@]}" pyproject.toml -o requirements.txt
grep -E '^[A-Za-z0-9_.-]+==' requirements.txt | cut -d' ' -f1 > .pins.txt
trap 'rm -f .pins.txt .tmp.txt' EXIT
grep -E '^huggingface-hub==' .pins.txt | "${compile[@]}" --no-annotate - -c .pins.txt -o requirements-preflight.txt
printf 'hatchling\nhatch-vcs\nsetuptools\n' | "${compile[@]}" --no-annotate - -o build-constraints.txt
for f in requirements.txt requirements-preflight.txt build-constraints.txt; do
  { echo "$header"; cat "$f"; } > .tmp.txt && mv .tmp.txt "$f"
done
